"""
Variaveis guardam valores para usarmos depois.
Em Python nao precisamos escrever o tipo antes do nome da variavel.
"""

nome = "Ana"
idade = 22
saldo = 150.75
tem_cadastro = True

print("Nome:", nome)
print("Idade:", idade)
print("Saldo:", saldo)
print("Tem cadastro?", tem_cadastro)

# O valor de uma variavel pode mudar durante o programa.
idade = idade + 1
print("Idade no proximo ano:", idade)

